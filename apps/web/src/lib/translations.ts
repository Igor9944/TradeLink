export function translateText(text: string, locale: AppLocale): string {
  return locale === 'fr' ? text : messages[locale][text] ?? text
}

export function getLocalizedValue(
  value: Partial<Record<AppLocale, string>> | null | undefined,
  locale: AppLocale,
): string {
  if (!value) return ''
  return value[locale] || value.fr || value.en || value.ar || ''
}
